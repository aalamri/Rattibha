function tr(s) {
  if (typeof window !== 'undefined' && window.__lang === 'ar') return AR[s] || s;
  return s;
}
function trCity(c) { return (typeof window !== 'undefined' && window.__lang === 'ar' && CITY_AR[c]) || c; }
