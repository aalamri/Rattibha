const NUM_AR = { '0':'٠','1':'١','2':'٢','3':'٣','4':'٤','5':'٥','6':'٦','7':'٧','8':'٨','9':'٩' };
function trMonth(m) { return (typeof window !== 'undefined' && window.__lang === 'ar' && MONTH_AR[m]) || m; }
function trNum(s) { return (typeof window !== 'undefined' && window.__lang === 'ar') ? String(s).replace(/[0-9]/g, d => NUM_AR[d]) : s; }
// localize a date like "14 Mar 2026" or "02 May 2026"
function trDate(s) {
  if (typeof window === 'undefined' || window.__lang !== 'ar') return s;
  return String(s).replace(/[A-Za-z]{3}/g, w => MONTH_AR[w] || w).replace(/[0-9]/g, d => NUM_AR[d]);
}
const isAR = () => typeof window !== 'undefined' && window.__lang === 'ar';

